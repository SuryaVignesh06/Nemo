/**
 * NEMO — stroke-based handwriting font.
 *
 * Every glyph is a list of pen strokes, not an outline: the renderer traces
 * them the way a hand would, so progressive drawing and the pen cursor come out
 * of the same data. Coordinates live in an em box where
 *
 *   y = 0.00  cap height (top of uppercase and digits)
 *   y = 0.42  x-height (top of lowercase bowls)
 *   y = 1.00  baseline
 *   y = 1.30  descender depth
 *
 * x runs from 0 to the glyph's advance width. Sizes are multiplied by the
 * requested font size at build time.
 */

export type Pt = [number, number];

export interface Glyph {
  /** Advance width in em units. */
  w: number;
  /** Ordered pen strokes. */
  strokes: Pt[][];
}

/**
 * Elliptical arc sampled into a polyline. Angles are degrees in a y-down
 * space: 0 = right, 90 = below centre, 180 = left, 270 = above centre.
 */
function arc(
  cx: number,
  cy: number,
  rx: number,
  ry: number,
  a0: number,
  a1: number,
  steps = 16
): Pt[] {
  const pts: Pt[] = [];
  for (let i = 0; i <= steps; i++) {
    const a = ((a0 + ((a1 - a0) * i) / steps) * Math.PI) / 180;
    pts.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return pts;
}

/** A closed oval, the workhorse for o/0/O and letter bowls. */
const oval = (cx: number, cy: number, rx: number, ry: number, from = 270): Pt[] =>
  arc(cx, cy, rx, ry, from, from + 360, 20);

const seg = (x0: number, y0: number, x1: number, y1: number): Pt[] => [
  [x0, y0],
  [x1, y1],
];

const G: Record<string, Glyph> = {};
const def = (ch: string, w: number, strokes: Pt[][]) => {
  G[ch] = { w, strokes };
};

