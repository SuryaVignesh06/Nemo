/** ASCII & Unicode fallbacks for characters we render with a nicer glyph. */
const SUBSTITUTIONS: Record<string, string> = {
  '–': '-',
  '—': '-',
  '‘': "'",
  '’': "'",
  '“': '"',
  '”': '"',
  '·': '*',
  '•': '•',
  '▪': '•',
  '▫': '•',
  '◆': '•',
  '✓': 'v',
  '✔': 'v',
  '✕': 'x',
  '✖': 'x',
  '★': '*',
  '☆': '*',
  '…': '.',
  '−': '-',
  '∗': '*',
};

/** Look up a glyph, substituting or falling back gracefully. */
export function glyphFor(ch: string): Glyph {
  if (G[ch]) return G[ch];
  const sub = SUBSTITUTIONS[ch];
  if (sub && G[sub]) return G[sub];
  const upper = ch.toUpperCase();
  if (G[upper]) return G[upper];
  const lower = ch.toLowerCase();
  if (G[lower]) return G[lower];
  // Unknown or whitespace character: clean space or subtle dot, never an ugly 0-like box
  if (/\s/.test(ch)) {
    return { w: 0.32, strokes: [] };
  }
  return {
    w: 0.35,
    strokes: [oval(0.18, 0.68, 0.04, 0.04)],
  };
}

export function hasGlyph(ch: string): boolean {
  return Boolean(G[ch] || SUBSTITUTIONS[ch] || G[ch.toLowerCase()] || G[ch.toUpperCase()]);
}

/** Total advance width of a string, in em units. */
export function measureEm(text: string, letterSpacing = 0.04): number {
  let w = 0;
  for (const ch of text) w += glyphFor(ch).w + letterSpacing;
  return Math.max(0, w - letterSpacing);
}

